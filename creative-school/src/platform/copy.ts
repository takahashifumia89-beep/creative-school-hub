export function useCopy() {
  const { t } = useLocale();
  return (source: string, values: unknown[] = []) => {
    let template = copy[source];
    if (!template && values.length === 0) {
      for (const [pattern, entry] of Object.entries(copy)) {
        if (!pattern.includes("{")) continue;
        const pieces = pattern.split(/(\{\d+\})/g);
        const escaped = pieces
          .map((part) =>
            /^\{\d+\}$/.test(part)
              ? "(.+?)"
              : part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"),
          )
          .join("");
        const match = source.match(new RegExp("^" + escaped + "$"));
        if (match) {
          template = entry;
          values = match.slice(1);
          break;
        }
      }
    }
    const translated = template ? t(template) : source;
    return translated.replace(/\{(\d+)\}/g, (_, i) =>
      String(values[Number(i)] ?? ""),
    );
  };
}
